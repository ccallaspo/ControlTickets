<h2 class="pdf-section-title">Metodología</h2>
<p>La capacitación se desarrollará en modalidad sincrónica, con clases en vivo a través de la plataforma de aula virtual de OTEC PROYECTA, en los días y horarios acordados con el cliente. El participante accederá con un usuario y contraseña que se le enviará días previos al inicio del curso.</p>
<p>El aprendizaje sincrónico implica encuentros en tiempo real con el relator, favoreciendo la interacción, el trabajo colaborativo y la resolución inmediata de consultas durante las sesiones programadas.</p>

<h2 class="pdf-section-title">Soporte</h2>
<p>Se dispondrá de soporte académico y técnico para el acceso y uso de la plataforma Moodle, brindando asistencia a los participantes en procesos de ingreso, navegación, recuperación de credenciales y utilización de los recursos disponibles, asegurando una adecuada experiencia de aprendizaje.</p>

