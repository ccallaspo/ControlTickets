<h2 class="pdf-section-title">Metodología</h2>
<p>La capacitación se desarrollará en modalidad e-learning, Asincrónica, con clases a través de plataforma de aula virtual de OTEC PROYECTA, al que el participante accederá con un usuario y contraseña que se le enviará días previos a que comience el curso, durante el tiempo que curso se encuentre vigente.</p>
<p>El aprendizaje asincrónico consiste en un modelo pedagógico que no sucede en tiempo real. Esta modalidad se da por medio de recursos y materiales educativos previamente elaborados, a los cuales tienen acceso los estudiantes en cualquier momento y lugar, lo que les permite aprender a su propio ritmo.</p>

<h2 class="pdf-section-title">Soporte</h2>
<p>Se dispondrá de soporte académico y técnico para el acceso y uso de la plataforma Moodle, brindando asistencia a los participantes en procesos de ingreso, navegación, recuperación de credenciales y utilización de los recursos disponibles, asegurando una adecuada experiencia de aprendizaje.</p>

<h2 class="pdf-section-title">Reportabilidad</h2>
<p>El curso contará con reportes semanales de seguimiento, los cuales incluirán asistencia de los participantes, participación en las actividades y observaciones relevantes del proceso formativo. Estos informes serán enviados al área responsable designada por la empresa.</p>

<h2 class="pdf-section-title">Evaluación</h2>
<ol>
    <li>Evaluación diagnóstica</li>
    <li>Evaluaciones intermedias (para evaluar aprendizajes del módulo)</li>
    <li>Evaluación final (100%)</li>
</ol>
<p>La nota mínima de aprobación es 4, en la escala de 1 a 7 y con un 75% de participación como mínimo.</p>

